import { api } from '../services/api';

/**
 * Converts a Base64 URL string (VAPID public key format) to a Uint8Array.
 */
export function urlBase64ToUint8Array(base64String: string): Uint8Array {
  const padding = '='.repeat((4 - (base64String.length % 4)) % 4);
  const base64 = (base64String + padding).replace(/-/g, '+').replace(/_/g, '/');
  const rawData = window.atob(base64);
  const outputArray = new Uint8Array(rawData.length);
  for (let i = 0; i < rawData.length; ++i) {
    outputArray[i] = rawData.charCodeAt(i);
  }
  return outputArray;
}

/**
 * Verifies if Push API and Service Worker notifications are supported by the client browser.
 */
export function isPushNotificationSupported(): boolean {
  return 'serviceWorker' in navigator && 'PushManager' in window && 'Notification' in window;
}

/**
 * Retrieves the current push subscription object from the active service worker.
 */
export async function getCurrentPushSubscription(): Promise<PushSubscription | null> {
  if (!isPushNotificationSupported()) return null;
  try {
    const registration = await navigator.serviceWorker.ready;
    return await registration.pushManager.getSubscription();
  } catch (err) {
    console.warn('Failed to retrieve push subscription:', err);
    return null;
  }
}

/**
 * Requests notification permission, obtains a Web Push subscription from the browser,
 * and posts the credentials to the backend API.
 */
export async function subscribeUserToPush(): Promise<{
  success: boolean;
  subscription?: PushSubscription;
  message?: string;
}> {
  if (!isPushNotificationSupported()) {
    return { success: false, message: 'Push notifications are not supported by this browser.' };
  }

  const permission = await Notification.requestPermission();
  if (permission !== 'granted') {
    return { success: false, message: 'Notification permission was denied by the user.' };
  }

  try {
    // 1. Fetch public VAPID key from backend
    const res = await api.get('/notifications/vapid-public-key');
    if (!res?.success || !res?.data?.publicKey) {
      return { success: false, message: 'Failed to retrieve VAPID public key from server.' };
    }

    const publicKey = res.data.publicKey;
    const applicationServerKey = urlBase64ToUint8Array(publicKey);

    // 2. Subscribe browser push manager
    const registration = await navigator.serviceWorker.ready;
    const subscription = await registration.pushManager.subscribe({
      userVisibleOnly: true,
      applicationServerKey: applicationServerKey as BufferSource,
    });

    const subJson = subscription.toJSON();
    const endpoint = subJson.endpoint;
    const p256dh = subJson.keys?.p256dh;
    const auth = subJson.keys?.auth;

    if (!endpoint || !p256dh || !auth) {
      return { success: false, message: 'Invalid subscription payload generated by browser.' };
    }

    // 3. Register subscription on backend server
    const apiRes = await api.post('/notifications/subscribe', {
      endpoint,
      p256dh,
      auth,
    });

    if (!apiRes?.success) {
      return {
        success: false,
        message: apiRes?.message || 'Failed to register subscription on server.',
      };
    }

    return { success: true, subscription };
  } catch (err: any) {
    console.error('Error subscribing to push notifications:', err);
    return { success: false, message: err.message || 'An error occurred during push subscription.' };
  }
}

/**
 * Cancels active browser push subscription and updates server records.
 */
export async function unsubscribeUserFromPush(): Promise<boolean> {
  const subscription = await getCurrentPushSubscription();
  if (subscription) {
    await subscription.unsubscribe();
    return true;
  }
  return false;
}

/**
 * Triggers a test Web Push notification request to the backend for the current user.
 */
export async function sendTestPushNotification(): Promise<{ success: boolean; message: string }> {
  try {
    const res = await api.post('/notifications/test-push', {});
    return { success: res.success, message: res.message || 'Test push notification dispatched.' };
  } catch (err: any) {
    return { success: false, message: err.message || 'Failed to send test push notification.' };
  }
}
